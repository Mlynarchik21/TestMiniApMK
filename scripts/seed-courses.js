async function main() {
  const client = new Client({ connectionString: DB_URL });
  await client.connect();
  console.log("Connected");

  // Clear existing
  await client.query(`DELETE FROM "LessonProgress"`);
  await client.query(`DELETE FROM "Question"`);
  await client.query(`DELETE FROM "Lesson"`);
  await client.query(`DELETE FROM "Course"`);
  console.log("Cleared existing course data");

  const courseId = cuid();
  const now = new Date().toISOString();

  await client.query(
    `INSERT INTO "Course" ("id","title","description","order","published","createdAt","updatedAt")
     VALUES ($1,$2,$3,$4,$5,$6,$7)`,
    [courseId, COURSE.title, COURSE.description, COURSE.order, true, now, now]
  );
  console.log("Created course:", courseId);

  for (const lesson of COURSE.lessons) {
    const lessonId = cuid();
    await client.query(
      `INSERT INTO "Lesson" ("id","courseId","title","moduleTitle","order","slides","createdAt","updatedAt")
       VALUES ($1,$2,$3,$4,$5,$6::jsonb,$7,$8)`,
      [
        lessonId,
        courseId,
        lesson.title,
        lesson.moduleTitle,
        lesson.order,
        JSON.stringify(lesson.slides),
        now,
        now,
      ]
    );

    for (let qi = 0; qi < lesson.questions.length; qi++) {
      const q = lesson.questions[qi];
      const qId = cuid();
      await client.query(
        `INSERT INTO "Question" ("id","lessonId","text","options","answer","order")
         VALUES ($1,$2,$3,$4::jsonb,$5,$6)`,
        [qId, lessonId, q.text, JSON.stringify(q.options), q.answer, qi]
      );
    }

    console.log(`  Lesson ${lesson.order}: ${lesson.title} (${lesson.questions.length} questions)`);
  }

  console.log("Seed complete!");
  await client.end();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
